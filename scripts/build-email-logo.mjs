/**
 * Bakes public/email/logo.png into a TS module.
 *
 * The logo is attached to every email inline (cid:), not linked. Reading the
 * file at runtime would mean relying on public/ being present in the serverless
 * bundle, which isn't guaranteed — so the bytes are committed instead.
 *
 * Run after changing the logo:  node scripts/build-email-logo.mjs
 */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const png = readFileSync(join(root, "public/email/logo.png"));
const base64 = png.toString("base64");

writeFileSync(
  join(root, "src/lib/email/logo-data.ts"),
  `// Generated by scripts/build-email-logo.mjs from public/email/logo.png.
// Do not edit by hand — re-run the script instead.

/** 392x68 PNG, displayed at 196x34 so it stays sharp on high-density screens. */
export const LOGO_PNG_BASE64 =
  "${base64}";

export const LOGO_CID = "fagc-logo";
export const LOGO_WIDTH = 196;
export const LOGO_HEIGHT = 34;
`,
);

console.log(`wrote src/lib/email/logo-data.ts (${(base64.length / 1024).toFixed(1)} KB base64)`);
